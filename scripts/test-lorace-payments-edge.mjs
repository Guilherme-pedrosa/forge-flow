import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
import { createHmac } from 'node:crypto';
const source=await fs.readFile(new URL('../supabase/functions/lorace-payments/mercadopago.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {verifySignature,checkoutUrl,assertPayment}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const secret='qa-webhook-secret-only',now=1792868400000,stamp=String(now),id='123456789',request='req-qa';
const hash=createHmac('sha256',secret).update(`id:${id};request-id:${request};ts:${stamp};`).digest('hex');
assert.equal(await verifySignature(secret,`ts=${stamp},v1=${hash}`,request,id,now),true);
assert.equal(await verifySignature(secret,`ts=${stamp},v1=${hash}`,request,'999',now),false);
assert.equal(await verifySignature(secret,`ts=${stamp},v1=${hash}`,request,id,now+700000),false);
assert.equal(await verifySignature(secret,`ts=${stamp},v1=${hash}`,null,id,now),false);
assert.equal(await verifySignature('wrong',`ts=${stamp},v1=${hash}`,request,id,now),false);
for(const url of ['http://www.mercadopago.com.br/checkout/v1','https://www.mercadopago.com.br.evil.test/checkout/v1','https://user:password@www.mercadopago.com.br/checkout/v1','javascript:alert(1)'])assert.throws(()=>checkoutUrl(url));
assert.equal(checkoutUrl('https://www.mercadopago.com.br/checkout/v1/redirect?pref_id=qa'),'https://www.mercadopago.com.br/checkout/v1/redirect?pref_id=qa');
